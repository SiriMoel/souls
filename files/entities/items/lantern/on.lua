x = x + Random(-2, 2)
y = y + Random(-3, 3)
GameCreateCosmeticParticle(soul_sparks[soul], x, y, Random(0, 3), Random(-6, 6), Random(0, 30), nil, 1, 2, true, false, true, true, 0, 0)